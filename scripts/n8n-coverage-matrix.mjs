// Mines the installed n8n package for every credential type and classifies
// lmconn's coverage of it. Regenerates docs/n8n-connector-matrix.md.
//
//   node scripts/n8n-coverage-matrix.mjs [path-to-n8n-package]
//
// Classification rules (auth mechanism decides coverage, not the service):
//   *OAuth2Api.credentials.js  -> oauth2    — covered: lmconn oauth authorize/refresh (+ presets for many)
//   *OAuth1Api.credentials.js  -> oauth1    — gap: OAuth 1.0a signing not implemented
//   everything else            -> key       — covered via `http request --auth` when the API is REST+bearer/key
// Non-HTTP protocols (databases, SMTP, queues) are flagged by credential
// shape: properties with host/port/database, or no HTTP-ish fields at all.
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const n8nRoot = process.argv[2] || join(execSync('npm root -g').toString().trim(), 'n8n');
const base = join(n8nRoot, 'node_modules', 'n8n-nodes-base', 'dist');
const credDir = join(base, 'credentials');
const presets = JSON.parse(execSync('cat src/oauth-presets.json', { encoding: 'utf8' }));
const n8nVersion = require(join(n8nRoot, 'package.json')).version;

const NON_HTTP = /postgres|mysql|mariadb|mongodb|redis|questdb|cockroachdb|timescaledb|snowflake|ftp|sftp|smtp|imap|mqtt|amqp|rabbitmq|kafka|nats|ldap|ssh|elasticsearch|clickhouse|surrealdb|supabase.*(db|postgres)/i;

const rows = [];
for (const file of readdirSync(credDir)) {
  if (!file.endsWith('.credentials.js')) continue;
  let inst;
  try {
    const mod = require(join(credDir, file));
    const cls = Object.values(mod).find((v) => typeof v === 'function');
    inst = new cls();
  } catch { continue; }
  const name = inst.name;
  const family = file.includes('OAuth2Api') ? 'oauth2' : file.includes('OAuth1Api') ? 'oauth1' : 'key';
  const key = name.replace(/OAuth2Api$|OAuth1Api$|Api$/, '').replace(/[A-Z]/g, (c, i) => (i ? '-' : '') + c.toLowerCase());
  const propNames = (inst.properties || []).map((p) => p.name).join(' ');
  const nonHttp = NON_HTTP.test(name) || NON_HTTP.test(inst.displayName ?? '');
  rows.push({ name, display: inst.displayName ?? name, key, family, nonHttp });
}

const count = (fn) => rows.filter(fn).length;
const oauth2 = rows.filter((r) => r.family === 'oauth2');
const withPreset = oauth2.filter((r) => presets[r.key]);
const nodeFiles = readdirSync(join(base, 'nodes'), { recursive: true }).filter((f) => String(f).endsWith('.node.js')).length;

const md = `# n8n connector coverage matrix (generated ${new Date().toISOString().slice(0, 10)})

Generated by \`scripts/n8n-coverage-matrix.mjs\` from the installed n8n
package — the true denominator, not marketing numbers. n8n ${n8nVersion} ships
**${rows.length} credential types** and **${nodeFiles} node files**.

## By auth mechanism

| Auth family | n8n credential types | lmconn status |
|---|---|---|
| OAuth2 | ${oauth2.length} | **Covered**: \`lmconn oauth authorize/refresh\` + auto-refresh in \`http request --auth\`. ${withPreset.length} have built-in presets (endpoints mined from n8n itself); the rest take \`--auth-url\`/\`--token-url\` once. |
| API key / header / query / basic | ${count((r) => r.family === 'key' && !r.nonHttp)} | **Covered generically**: \`lmconn cred set S api_key\` + \`http request --auth S\`. |
| OAuth 1.0a | ${count((r) => r.family === 'oauth1')} | **Gap**: request signing not implemented. |
| Non-HTTP protocols (SQL, SMTP, FTP, queues…) | ${count((r) => r.nonHttp)} | **Gap**: needs drivers, not HTTPS calls. |

## What "covered" means — and what it does not

Covered = **auth + transport**: lmconn can authenticate and call the service's
REST API today, with secrets in the SQLite store and JSON envelopes out.
Not implied: the 400+ per-service convenience operations n8n ships as named
nodes ("Slack: post message" with validated fields). Those remain URLs and
JSON bodies in the script — by design, since agents write calls faster than
they browse node catalogs. Dedicated ops are added per AGENTS.md only where
validation or ergonomics pay off (so far: github).

Also still missing beyond auth: webhook/trigger receivers (lmscript polls or
system cron instead), OAuth2 client-credentials grant, request signing
(AWS SigV4, HMAC).

## OAuth2 services without a preset

These ${oauth2.length - withPreset.length} n8n OAuth2 credentials have no row
in \`src/oauth-presets.json\` (their n8n definition uses runtime expressions or
non-standard fields — see the extractor's skip log). They still work with two
flags (\`--auth-url\`, \`--token-url\`).

${oauth2.filter((r) => !presets[r.key]).map((r) => `- ${r.display} (\`${r.name}\`)`).join('\n')}
`;

writeFileSync(new URL('../docs/n8n-connector-matrix.md', import.meta.url), md);
console.log(`credential types: ${rows.length} | oauth2: ${oauth2.length} (presets: ${withPreset.length}) | key: ${count((r) => r.family === 'key' && !r.nonHttp)} | oauth1: ${count((r) => r.family === 'oauth1')} | non-http: ${count((r) => r.nonHttp)} | node files: ${nodeFiles}`);
